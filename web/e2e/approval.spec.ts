import { expect, test } from '@playwright/test';

test('agency requests copy and client approves revised content', async ({page,browser}) => {
  const email=process.env.LAUNCHFLOW_TEST_EMAIL;
  const password=process.env.LAUNCHFLOW_TEST_PASSWORD;
  if(!email||!password) throw new Error('Provision a synthetic test owner and set the test credentials.');
  page.on('dialog',dialog=>void dialog.accept());
  await page.goto('/login');
  await page.getByLabel('Email').fill(email);
  await page.getByLabel('Password').fill(password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByLabel('Project name').fill('Synthetic launch '+Date.now());
  await page.getByRole('button',{name:'Create project',exact:true}).click();
  await page.getByLabel('Page or item title').fill('Homepage copy');
  await page.getByLabel('Client instructions').fill('Please provide a headline.');
  await page.getByRole('button',{name:'Add request',exact:true}).click();
  await page.getByRole('button',{name:'Create or rotate link'}).click();
  const link=await page.getByLabel('Client link').inputValue();
  const ctx=await browser.newContext({viewport:{width:390,height:844}});
  try {
    const client=await ctx.newPage();
    await client.goto(link);
    await expect(client).toHaveURL(/\/client$/);
    await client.getByLabel('Website copy or reference URL').fill('Original headline');
    await client.getByRole('button',{name:'Submit content'}).click();
    await expect(client.locator('.badge').filter({hasText:'submitted'})).toBeVisible();
    await page.getByRole('button',{name:'Refresh project'}).click();
    await page.getByLabel('Edit copy').fill('Final headline');
    await page.getByRole('button',{name:'Save revision'}).click();
    await expect(page.getByText('Latest revision · v2')).toBeVisible();
    await page.getByRole('button',{name:'Share saved version'}).click();
    await expect(page.locator('.badge').filter({hasText:'in review'})).toBeVisible();
    await client.getByRole('button',{name:'Refresh project'}).click();
    await expect(client.getByText('Final headline',{exact:true})).toBeVisible();
    await client.getByRole('button',{name:'Approve version'}).click();
    await expect(client.getByText('Content ready',{exact:true})).toBeVisible();
    await page.getByRole('button',{name:'Refresh project'}).click();
    await expect(page.getByText('Content ready',{exact:true})).toBeVisible();
    await page.getByRole('button',{name:'View history'}).click();
    await page.getByText(/^Version 2/).click();
    await expect(page.getByText(/^Approved ·/)).toBeVisible();
    await page.getByRole('button',{name:'Draft from checklist'}).click();
    await expect(page.getByRole('button',{name:'Copy note'})).toBeDisabled();
    await page.getByLabel('I reviewed this draft').check();
    await expect(page.getByRole('button',{name:'Copy note'})).toBeEnabled();
    await page.getByRole('button',{name:'Revoke link'}).click();
    await expect(page.getByText('Client access revoked.')).toBeVisible();
    await client.reload();
    await expect(client.getByText('Ask your agency for a fresh link.')).toBeVisible();
  } finally { await ctx.close(); }
});
